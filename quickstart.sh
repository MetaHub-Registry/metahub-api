#!/usr/bin/env bash
# MetaHub quickstart — one command from a fresh clone.
#
#   ./quickstart.sh          start the stack (generates credentials on first run)
#   ./quickstart.sh stop     stop it, keep the data
#   ./quickstart.sh clean    stop it and remove the data volumes
#
# The stack pulls published images; it builds nothing, needs no Go toolchain and
# no sibling checkouts. Credentials are generated once into .quickstart.env.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

env_file=.quickstart.env
compose=(docker compose --env-file "$env_file" -f docker-compose-quickstart.yaml)
# the UI image is published from metahub-ui; CI builds only this repo, so it can
# start the stack without it
profile=()
[ "${QUICKSTART_SKIP_UI:-0}" = "1" ] || profile=(--profile ui)

rand() { # rand <bytes> → hex, default 12 bytes
  local n="${1:-12}"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$n"
  else
    od -An -N"$n" -tx1 /dev/urandom | tr -d ' \n'
  fi
}

generate_env() {
  umask 077
  cat > "$env_file" <<EOF
# Generated by ./quickstart.sh — keep this file, it holds the only copy of the
# credentials. Delete it together with the data volumes ('./quickstart.sh clean').
METAHUB_VERSION=${METAHUB_VERSION:-latest}
MINIO_ROOT_USER=metahub
MINIO_ROOT_PASSWORD=$(rand)
NEO4J_USER=neo4j
NEO4J_PASSWORD=$(rand)
GODMODE_USER=admin
GODMODE_PASSWORD=$(rand)
GODMODE_SIGNING_KEY=$(rand 24)  # the API requires at least 32 characters
EOF
}

case "${1:-start}" in
  start)
    if ! docker info >/dev/null 2>&1; then
      echo "error: no Docker daemon reachable" >&2
      exit 1
    fi
    fresh=0
    if [ ! -f "$env_file" ]; then
      generate_env
      fresh=1
      echo "generated credentials in $env_file"
    fi

    "${compose[@]}" "${profile[@]}" up -d --wait

    # shellcheck disable=SC1090
    . "./$env_file"
    printf '\nMetaHub is up:\n\n'
    printf '  registry    http://localhost:8080\n'
    [ "${#profile[@]}" -gt 0 ] && printf '  web UI      http://localhost:8082\n'
    printf '  S3          http://localhost:9000   (console http://localhost:9001)\n'
    printf '  login       %s / %s\n' "$GODMODE_USER" "$GODMODE_PASSWORD"
    if [ "$fresh" -eq 1 ]; then
      printf '\nThe password is also in %s — that file is the only copy.\n' "$env_file"
    fi
    printf '\nStop with ./quickstart.sh stop, remove data with ./quickstart.sh clean.\n'
    ;;
  stop)
    [ -f "$env_file" ] || { echo "nothing to stop" ; exit 0; }
    "${compose[@]}" "${profile[@]}" down
    ;;
  clean)
    [ -f "$env_file" ] || { echo "nothing to clean" ; exit 0; }
    "${compose[@]}" "${profile[@]}" down -v
    echo "data volumes removed; $env_file kept (delete it yourself if you want new credentials)"
    ;;
  *)
    echo "usage: $0 [start|stop|clean]" >&2
    exit 2
    ;;
esac
