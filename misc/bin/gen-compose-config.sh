#!/usr/bin/env bash
# Generate the local compose configuration with unique credentials.
#
#   ./misc/bin/gen-compose-config.sh [--force]
#
# Writes:
#   misc/config/compose-config.yaml   read by the API and the admin CLI
#   misc/config/compose.env           read by docker compose (--env-file)
#
# Both are ignored by Git. Values may be supplied through the environment;
# anything unset is generated. The generated admin/user accounts are printed
# once — they are not recoverable afterwards unless you read the files.
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "${script_dir}/../.." && pwd)"

example="${repo_root}/misc/config/compose-config.example.yaml"
config="${repo_root}/misc/config/compose-config.yaml"
env_file="${repo_root}/misc/config/compose.env"

force=0
for arg in "$@"; do
  case "$arg" in
    --force) force=1 ;;
    -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

if [ ! -f "$example" ]; then
  echo "error: missing template $example" >&2
  exit 1
fi

if { [ -f "$config" ] || [ -f "$env_file" ]; } && [ "$force" -ne 1 ]; then
  echo "error: configuration already exists:" >&2
  [ -f "$config" ] && echo "  $config" >&2
  [ -f "$env_file" ] && echo "  $env_file" >&2
  echo "re-run with --force to overwrite" >&2
  exit 1
fi

rand() {
  # 24 hex characters; falls back to /dev/urandom when openssl is absent
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "${1:-12}"
  else
    od -An -N "${1:-12}" -tx1 /dev/urandom | tr -d ' \n'
  fi
}

MINIO_ROOT_USER="${MINIO_ROOT_USER:-minio}"
MINIO_ROOT_PASSWORD="${MINIO_ROOT_PASSWORD:-$(rand 12)}"
NEO4J_USER="${NEO4J_USER:-neo4j}"
NEO4J_PASSWORD="${NEO4J_PASSWORD:-$(rand 12)}"
ADMIN_USERNAME="${ADMIN_USERNAME:-oci}"
ADMIN_PASSWORD="${ADMIN_PASSWORD:-$(rand 12)}"
USER_USERNAME="${USER_USERNAME:-demo}"
USER_PASSWORD="${USER_PASSWORD:-$(rand 12)}"
GODMODE_SIGNING_KEY="${GODMODE_SIGNING_KEY:-$(rand 24)}"

# Substitute only the documented tokens; leave every other line untouched.
# Escape sed replacement metacharacters so env-supplied values stay literal.
esc() { printf '%s' "$1" | sed 's/[\\&|]/\\&/g'; }

tmp="$(mktemp "${config}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
sed \
  -e "s|__MINIO_ROOT_USER__|$(esc "$MINIO_ROOT_USER")|g" \
  -e "s|__MINIO_ROOT_PASSWORD__|$(esc "$MINIO_ROOT_PASSWORD")|g" \
  -e "s|__NEO4J_USER__|$(esc "$NEO4J_USER")|g" \
  -e "s|__NEO4J_PASSWORD__|$(esc "$NEO4J_PASSWORD")|g" \
  -e "s|__ADMIN_USERNAME__|$(esc "$ADMIN_USERNAME")|g" \
  -e "s|__ADMIN_PASSWORD__|$(esc "$ADMIN_PASSWORD")|g" \
  -e "s|__USER_USERNAME__|$(esc "$USER_USERNAME")|g" \
  -e "s|__USER_PASSWORD__|$(esc "$USER_PASSWORD")|g" \
  -e "s|__GODMODE_SIGNING_KEY__|$(esc "$GODMODE_SIGNING_KEY")|g" \
  "$example" > "$tmp"
mv "$tmp" "$config"
trap - EXIT
chmod 600 "$config"

umask 077
cat > "$env_file" <<EOF
# Generated by misc/bin/gen-compose-config.sh — ignored by Git.
MINIO_ROOT_USER=${MINIO_ROOT_USER}
MINIO_ROOT_PASSWORD=${MINIO_ROOT_PASSWORD}
NEO4J_USER=${NEO4J_USER}
NEO4J_PASSWORD=${NEO4J_PASSWORD}
OCONF_USERNAME=${ADMIN_USERNAME}
OCONF_PASSWORD=${ADMIN_PASSWORD}
GODMODE_SIGNING_KEY=${GODMODE_SIGNING_KEY}
EOF

echo "wrote $config"
echo "wrote $env_file"
echo
echo "registry accounts (registry login):"
echo "  admin: ${ADMIN_USERNAME} / ${ADMIN_PASSWORD}"
echo "  user:  ${USER_USERNAME} / ${USER_PASSWORD}"
